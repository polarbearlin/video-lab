"""dialogue_60s_v2.wav + its timeline -> voice60.js: the 9 lines (speaker, start, end, text) and a per-frame (30 fps)
mouth envelope of the speaking voice (0..9), so the film's lip flap and head motion follow the approved track."""
import json, sys, numpy as np, soundfile as sf

src = sys.argv[1] if len(sys.argv) > 1 else '/tmp/in/handoff_60s'
TEXT = ['小姐，下雪了。', '这么冷还叫我出来？北极熊你是不是想冻死我！', '……哼，这还差不多。', '笑什么笑！再笑扣你工资。',
        '慢点慢点——', '好吧，再快一点！', '像您。', '哪里像！', '……眼睛挺像的。']
tl = json.load(open(f'{src}/dialogue_60s_timeline_v2.json'))
d, sr = sf.read(f'{src}/dialogue_60s_v2.wav')
if d.ndim > 1: d = d.mean(1)
fps, n = 30, int(round(len(d) / sr * 30))
hop = sr // fps
rms = np.array([np.sqrt(np.mean(d[i * hop:(i + 1) * hop] ** 2) + 1e-12) for i in range(n)])
db = 20 * np.log10(rms)
env = np.clip((db + 46) / 24, 0, 1)                 # -46 dBFS closed .. -22 dBFS wide open
env = np.convolve(env, [0.25, 0.5, 0.25], 'same')
lines = []
for i, L in enumerate(tl):
    who = 'butler' if '北极熊' in L['line'] else 'lady'
    lines.append({'id': i + 1, 'who': who, 'start': L['start'], 'end': L['end'], 'text': TEXT[i]})
mask = np.zeros(n)
for L in lines:
    mask[int(L['start'] * fps):int(np.ceil(L['end'] * fps)) + 1] = 1
env = env * mask
s = ''.join(str(int(round(v * 9))) for v in env)
open('first-snow/voice60.js', 'w').write(
    '// generated by make_voice.py from dialogue_60s_v2.wav and dialogue_60s_timeline_v2.json: do not edit\n'
    f'export const DURATION = {len(d) / sr:.3f};\n'
    f'export const LINES = {json.dumps(lines, ensure_ascii=False)};\n'
    f"export const ENV = '{s}';\n")
json.dump(lines, open('first-snow/lines.json', 'w'), ensure_ascii=False, indent=1)
print(n, 'frames;', sum(c != '0' for c in s), 'voiced')
